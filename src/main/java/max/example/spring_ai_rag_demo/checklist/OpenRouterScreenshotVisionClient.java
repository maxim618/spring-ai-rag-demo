package max.example.spring_ai_rag_demo.checklist;

import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.ai.chat.client.ChatClient;
import org.springframework.ai.openai.OpenAiChatOptions;
import org.springframework.core.io.ByteArrayResource;
import org.springframework.stereotype.Component;
import org.springframework.util.MimeType;

import java.util.Objects;

@Component
public class OpenRouterScreenshotVisionClient implements ScreenshotVisionClient {

    private static final Logger logger =
            LoggerFactory.getLogger(OpenRouterScreenshotVisionClient.class);

    private static final String EXTRACTION_PROMPT = """
            Ты — точный парсер интерфейса мобильного приложения. Твоя задача — извлечь первое сверху задание чек-листа и относящиеся к нему варианты ответа.
            Верни ответ СТРОГО в формате валидного JSON. Не используй Markdown-обёртки, комментарии и пояснения вне JSON.
            
             1. ВИЗУАЛЬНАЯ СТРУКТУРА ЭКРАНА
            Учитывай следующие особенности интерфейса:
            - Шапка экрана (слово «Чек-лист», время, системные иконки) — игнорируй.
            - Текст задания — жирный или полужирный тёмный текст, расположенный непосредственно на светло-сером фоне страницы.
            - Варианты ответа — отдельные белые закруглённые карточки под текстом задания.
            - Внутри каждой карточки слева находится текст варианта, справа — квадратный чекбокс.
            - Блоки без чекбокса (загрузка фото, подсказки, информационные плашки) вариантами ответа не являются — игнорируй их.
            - После вариантов текущего задания на сером фоне может начинаться следующее задание.
            - Внизу экрана поверх содержимого закреплена чёрная кнопка «Продолжить». Она может перекрывать часть следующего задания или вариантов ответа.
            Не ожидай, что задание и его варианты находятся внутри одной общей карточки или имеют общую рамку.
            
            2. ПОИСК ПЕРВОГО ЗАДАНИЯ И СБОР ВАРИАНТОВ
            2.1. Просматривай экран сверху вниз под шапкой «Чек-лист».
            2.2. Если в верхней части изображения видны только белые карточки с чекбоксами, но над ними нет текста задания на сером фоне, считай их остатком предыдущего вопроса и игнорируй.
            2.3. Найди первый самостоятельный текст задания на сером фоне.
            2.4. Собери белые карточки с чекбоксами, идущие непосредственно после этого задания. Сохраняй их исходный порядок.
            2.5. Прекрати сбор вариантов, как только на сером фоне появится следующий текст задания или закончится экран.
            2.6. Извлекай только первое найденное задание и его варианты. Не переходи к следующему заданию, даже если оно полностью или частично видно и читается лучше.
            2.7. Включай в answerOptions только те варианты, текст которых удалось уверенно распознать полностью. Если текст варианта закрыт кнопкой, обрезан или неразборчив, пропусти этот вариант. Не угадывай его содержимое.
            Не пытайся определить, сколько вариантов должно быть у задания. Не оценивай полноту списка и не делай вывод о пропущенных вариантах по их предполагаемому количеству.
            Задание может состоять из одного или нескольких предложений. Оно может заканчиваться точкой, вопросительным знаком, двоеточием или не иметь завершающего знака препинания. Не используй пунктуацию как единственный признак границ задания.
            
            3. ОБРАБОТКА КНОПКИ «ПРОДОЛЖИТЬ»
            Кнопка закреплена поверх нижней части экрана и может перекрывать содержимое.
            Различай следующие ситуации:
             - Если кнопка перекрывает следующее задание, игнорируй это задание. Его читаемость не влияет на результат.
             - Если кнопка перекрывает только свободную область или фон, продолжай распознавание.
             - Если кнопка перекрывает текст одного из вариантов текущего задания, не включай этот вариант в answerOptions. Остальные полностью распознанные варианты сохрани.
             - Если кнопка перекрывает часть текста самого первого выбранного задания и из-за этого его невозможно уверенно прочитать полностью, верни UNREADABLE.
             Перекрытие вариантов ответа само по себе не является основанием для UNREADABLE, если текст первого задания читается полностью.
            
            4. СТАТУСЫ РАСПОЗНАВАНИЯ
            Используй строго два статуса: READABLE и UNREADABLE.
            4.1. READABLE
            Используй READABLE, если полный текст первого выбранного задания удалось уверенно распознать.
            При этом:
             - В поле text помести полный распознанный текст задания.
             - В answerOptions включи только варианты, текст которых удалось распознать полностью и уверенно.
             - Если отдельные варианты обрезаны, перекрыты или неразборчивы, пропусти их.
             - Не угадывай отсутствующий текст.
             - Не пытайся определить ожидаемое количество вариантов.
             - Не считай отсутствие некоторых вариантов основанием для UNREADABLE.
             - Поле reason должно быть пустой строкой.
            READABLE означает, что само задание распознано. Этот статус не гарантирует, что удалось извлечь абсолютно все варианты ответа.
            4.2. UNREADABLE
            Используй UNREADABLE только в том случае, если текст первого выбранного задания невозможно надёжно прочитать полностью.
            Причины:
            - текст задания обрезан;
            - текст задания перекрыт элементами интерфейса;
            - текст задания слишком размыт или нечитаем;
            - невозможно уверенно определить границы самого задания.
            При UNREADABLE верни пустые text и answerOptions, а причину укажи в reason.
            Не переходи к следующему вопросу, если первый найденный вопрос нечитаем.
            
            5. ВАЖНОЕ РАЗГРАНИЧЕНИЕ
            Статус определяется исключительно читаемостью текста первого выбранного задания.
            Например:
            - Задание читается, все варианты читаются — READABLE.
            - Задание читается, один вариант перекрыт кнопкой — READABLE. Перекрытый вариант пропусти.
            - Задание читается, часть вариантов обрезана нижней границей экрана — READABLE. Включи только полностью распознанные варианты.
            - Задание читается, но следующий вопрос виден лишь частично или перекрыт кнопкой — READABLE.
            - Сам текст первого задания обрезан или нечитаем — UNREADABLE.
            Не определяй полноту списка вариантов по их количеству, расположению или предполагаемой структуре задания.
            
            6. ПРАВИЛА ИЗВЛЕЧЕНИЯ ТЕКСТА
            - Сохраняй оригинальную орфографию, пунктуацию, цифры, предлоги и отрицания.
            - Не исправляй грамматические и орфографические ошибки.
            - Не перефразируй текст.
            - Не дополняй отсутствующие фрагменты по смыслу.
            - Переносы строк внутри одного абзаца объединяй в одну строку через пробел.
            - Сохраняй порядок предложений и вариантов ответа.
            - Не анализируй, какие чекбоксы нажаты.
            - Не определяй правильность вариантов.
            - Не сопоставляй вопрос с базой знаний и не выбирай его идентификатор.
            - Не включай заголовки, кнопки и прочие элементы управления в текст задания или варианты ответа.
            
            7. ФОРМАТ ВЫВОДА JSON
            
            При распознанном тексте задания:
            
            {
              "status": "READABLE",
              "text": "Полный текст первого задания",
              "answerOptions": [
                "Текст первого полностью распознанного варианта",
                "Текст второго полностью распознанного варианта"
              ],
              "reason": ""
            }
            
            Если текст первого задания невозможно прочитать:
            
            {
              "status": "UNREADABLE",
              "text": "",
              "answerOptions": [],
              "reason": "Кратко укажи причину."
            }
            
            8. ОБЯЗАТЕЛЬНЫЕ ОГРАНИЧЕНИЯ
            
            - Возвращай ровно один JSON-объект.
            - status может принимать только значения READABLE или UNREADABLE.
            - При READABLE поле text должно содержать полный распознанный текст первого задания.
            - При READABLE поле answerOptions должно содержать только полностью распознанные варианты. Массив может быть пустым или содержать любое количество элементов.
            - При UNREADABLE поля text и answerOptions должны быть пустыми.
            - При READABLE поле reason должно быть строго пустой строкой "".
            - При UNREADABLE поле reason должно содержать краткое пояснение на русском языке.
            - Не добавляй новые поля.
            - Не заключай JSON в Markdown-блок.
            - Не возвращай текст, отсутствующий на изображении.
            """;

    private final ChatClient chatClient;
    private final String model;

    public OpenRouterScreenshotVisionClient(
            ChatClient.Builder chatClientBuilder,
            @org.springframework.beans.factory.annotation.Value(
                    "${knowledge.screenshot.model:nvidia/nemotron-3.5-super-vl:free}"
            ) String model
    ) {
        this.chatClient = Objects.requireNonNull(chatClientBuilder, "chatClientBuilder").build();
        this.model = Objects.requireNonNull(model, "model");
    }

    @Override
    public ScreenshotQuestionExtractionResponse extractTopmostQuestion(
            byte[] image,
            MimeType mimeType
    ) {
        try {
            return chatClient.prompt()
                    .options(OpenAiChatOptions.builder().model(model))
                    .user(user -> user
                            .text(EXTRACTION_PROMPT)
                            .media(mimeType, new ByteArrayResource(image)))
                    .call()
                    .entity(ScreenshotQuestionExtractionResponse.class);
        } catch (RuntimeException exception) {
            logger.error(
                    "Vision model request or response conversion failed; configuredModel={}",
                    model,
                    exception
            );
            throw new ScreenshotQuestionExtractionException(
                    "Vision model request failed", exception
            );
        }
    }
}
